// Regenerate platform assets from the workbench SVG mark.
import fs from "node:fs/promises";
import sharp from "sharp";
import { APP, TRAY, MARK } from "../desktop/scripts/icon-source.js";

const root = new URL("../", import.meta.url);
const source = await fs.readFile(new URL("web/icon.svg", root), "utf8");
// iOS applies the corner mask itself: provide an opaque, full-bleed square.
const square = source.replace(/(<rect\b[^>]*?)\s+rx="[^"]+"/, "$1");
await fs.writeFile(new URL("web/icon-maskable.svg", root), square);
const indexPath = new URL("web/index.html", root);
const index = await fs.readFile(indexPath, "utf8");
// Loading indicators share the actual mark, with transparent surroundings and center.
const loaderSvg = (id) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="76 76 360 360" aria-hidden="true">${MARK.replaceAll("loft-center", id)}</svg>`;
const inline = loaderSvg("loft-boot-center");
await fs.writeFile(indexPath, index.replace(/(<span class="loft-loader xl"[^>]*>)<svg[\s\S]*?<\/svg>(<\/span>)/, `$1${inline}$2`));
await fs.writeFile(new URL("web/lib/loft-mark.js", root), `// Generated by npm run icons from web/icon.svg.\nexport const LOFT_MOTION_MS = 1800;\nconst MARK = ${JSON.stringify(loaderSvg("loft-center"))};\nexport function loftLoaderSvg(id) { return MARK.replaceAll("loft-center", id); }\n`);
for (const [file, svg, size] of [
  ["web/apple-touch-icon.png", square, 180],
  ["desktop/build/icon.png", APP, 1024],
  ["desktop/assets/icon.png", APP, 256],
  ["desktop/assets/trayTemplate.png", TRAY, 18],
  ["desktop/assets/trayTemplate@2x.png", TRAY, 36],
]) {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(new URL(file, root).pathname);
  console.log(`${file} (${size}×${size})`);
}
