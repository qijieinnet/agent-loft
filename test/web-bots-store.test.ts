import { after, test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const home = fs.mkdtempSync(path.join(os.tmpdir(), "loft-web-bots-"));
process.env.AGENT_LOFT_HOME = home;
const users = await import("../src/core/users.js");
const db = await import("../src/core/db.js");
const bots = await import("../src/core/web-bots.js");
const addUser = (name: string) => users.createUser({ name, password: "testing-only!", role: "member" }).id;
const admin = users.createUser({ name: "admin", password: "testing-only!", role: "admin" }).id;
after(() => { db.closeDatabaseForTest(); fs.rmSync(home, { recursive: true, force: true }); });
const status = (n: number) => (err: unknown) => err instanceof bots.WebBotError && err.status === n;

test("默认 Bot、单人话题、成员共用与换届邀请", () => {
  const alice = addUser("alice"), bob = addUser("bob"), chris = addUser("chris");
  const [mine] = bots.listBots(alice);
  assert.ok(mine?.isDefault);
  assert.equal(mine.sharedThreadId, null);
  assert.equal(bots.listBots(alice)[0]?.privateThreadId, mine.privateThreadId);
  assert.throws(() => bots.getBot(admin, mine.id), status(404));
  bots.appendBotNotice(alice, mine.privateThreadId, "Alice 私聊");

  const bot = bots.createBot(alice, "一家人的助手");
  assert.equal(bots.renameBot(alice, bot.id, "家庭助手").name, "家庭助手");
  const rotated = bots.createInvite(alice, bot.id);
  const invite = bots.createInvite(alice, bot.id);
  assert.ok(!bots.validBotInvite(rotated.token) && bots.validBotInvite(invite.token));
  assert.throws(() => bots.acceptInvite(chris, rotated.token), status(404));
  assert.throws(() => bots.acceptInvite(alice, invite.token), status(400));
  const joined = bots.acceptInvite(bob, invite.token);
  assert.ok(!bots.validBotInvite(invite.token));
  const shared = joined.sharedThreadId!;
  assert.equal(bots.getBot(alice, bot.id).sharedThreadId, shared);
  assert.notEqual(joined.privateThreadId, bot.privateThreadId);
  assert.throws(() => bots.listMessages(bob, bot.privateThreadId), status(404));
  assert.throws(() => bots.getBotThread(alice, joined.privateThreadId), status(404));
  assert.throws(() => bots.getBotThread(chris, shared), status(404));
  assert.throws(() => bots.createInvite(bob, bot.id), status(404));
  assert.throws(() => bots.removeMember(bob, bot.id, alice), status(404));

  const first = bots.getBotThread(bob, shared);
  const started = bots.startTurn(bob, shared, "request1", "一起留意天气");
  assert.ok(started.started);
  assert.equal(bots.startTurn(bob, shared, "request1", "一起留意天气").message.id, started.message.id);
  assert.throws(() => bots.startTurn(alice, shared, "different", "第二条"), status(409));
  bots.removeMember(alice, bot.id, bob);
  assert.throws(() => bots.listMessages(bob, shared), status(404));
  bots.acceptInvite(bob, bots.createInvite(alice, bot.id).token);
  assert.notEqual(bots.getBotThread(bob, shared).accessId, first.accessId);
  assert.equal(bots.finishTurn(bob, shared, "request1", "迟来的结果"), undefined);
  assert.ok(bots.listMessages(alice, shared).every(m => m.status !== "pending"));
  bots.appendBotNotice(alice, shared, "共同的记录");
  assert.equal(bots.listMessages(bob, shared).at(-1)?.text, "共同的记录");
  bots.appendBotNotice(alice, bot.privateThreadId, "只有 Alice 可以看到");
  const bobBot = bots.listBots(bob).find(item => item.id === bot.id)!;
  assert.deepEqual(Object.keys(bobBot.previews), [shared]);
  assert.equal(bobBot.previews[shared]?.text, "共同的记录");
  const aliceBot = bots.listBots(alice).find(item => item.id === bot.id)!;
  assert.equal(aliceBot.previews[bot.privateThreadId]?.text, "只有 Alice 可以看到");
  bots.stopSharing(alice, bot.id);
  const reopened = bots.acceptInvite(chris, bots.createInvite(alice, bot.id).token);
  assert.notEqual(reopened.sharedThreadId, shared);
  assert.throws(() => bots.listMessages(chris, shared), status(404));
  assert.equal(bots.listMessages(chris, reopened.sharedThreadId!).length, 0);
  assert.deepEqual(bots.listBots(chris).find(item => item.id === bot.id)?.previews, {});
  assert.throws(() => bots.getBot(bob, bot.id), status(404));
});

test("照片有独立读取权限，轮次和图片经过重开数据库仍可找回", () => {
  const actor = addUser("photo"), outsider = addUser("outsider");
  const bot = bots.listBots(actor)[0]!;
  const thread = bot.privateThreadId;
  const image = { name: "日历.png", mediaType: "image/png", data: "aGVsbG8=" };
  const { message } = bots.startTurn(actor, thread, "with-photo", "图上写了什么？", [image]);
  assert.equal(message.images[0]?.data, undefined);
  assert.deepEqual(bots.getBotMessage(actor, thread, message.id)?.images, [image]);
  assert.throws(() => bots.getBotMessage(outsider, thread, message.id), status(404));
  bots.finishTurn(actor, thread, "with-photo", "带水壶");
  assert.equal(bots.finishTurn(actor, thread, "with-photo", "重复结果"), undefined);
  const next = bots.startTurn(actor, thread, "interrupted", "还有什么？");
  db.sql("UPDATE web_bot_messages SET createdAt=? WHERE id=?").run(Date.now() - 21 * 60_000, next.message.id);
  db.closeDatabaseForTest();
  bots.recoverPendingBotTurns();
  const history = bots.listMessages(actor, thread);
  assert.equal(history.length, 4);
  assert.equal(history[1]?.text, "带水壶");
  assert.equal(history[2]?.status, "failed");
  assert.match(history[3]!.text, /中断/);
  assert.equal(bots.startTurn(actor, thread, "interrupted", "还有什么？").started, false);
  assert.equal(bots.listMessages(actor, thread, 2, history[2]!.id).length, 2);
});

test("过期和停用的邀请无效，停用账号不能读取或提交回复", () => {
  const owner = addUser("enabled"), actor = addUser("disabled");
  const bot = bots.listBots(owner)[0]!;
  const expired = bots.createInvite(owner, bot.id);
  db.sql("UPDATE web_bot_invites SET expires=0 WHERE bot=?").run(bot.id);
  assert.equal(bots.validBotInvite(expired.token), false);
  assert.throws(() => bots.acceptInvite(actor, expired.token), status(404));
  const joined = bots.acceptInvite(actor, bots.createInvite(owner, bot.id).token);
  const oldAccess = bots.getBotThread(actor, joined.sharedThreadId!).accessId;
  bots.startTurn(actor, joined.sharedThreadId!, "interrupted", "尝试一下");
  users.updateUser(actor, { disabled: true });
  assert.throws(() => bots.getBotThread(actor, joined.sharedThreadId!), status(403));
  assert.equal(bots.finishTurn(actor, joined.sharedThreadId!, "interrupted", "结果"), undefined);
  users.updateUser(actor, { disabled: false });
  const renewed = bots.getBotThread(actor, joined.sharedThreadId!);
  assert.notEqual(renewed.accessId, oldAccess);
  assert.equal(db.sql("SELECT access_id FROM web_bot_members WHERE bot=? AND user=?").get(bot.id, actor)?.access_id, renewed.accessId);
  const token = bots.createInvite(owner, bot.id).token;
  users.updateUser(owner, { disabled: true });
  assert.equal(bots.validBotInvite(token), false);
  users.updateUser(owner, { disabled: false });
  assert.equal(bots.validBotInvite(token), false);
  assert.notEqual(bots.getBotThread(actor, joined.sharedThreadId!).accessId, renewed.accessId);
});
